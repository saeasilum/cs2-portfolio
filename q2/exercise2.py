# Exercise 2: The Countdown Timer
# This script counts down from 10 to 1 using a while loop and then prints a message.
# A while loop is used because the loop runs as long as the condition remains true.

# Set the starting number for the countdown
count = 10

# The while loop runs continuously as long as count is greater than 0
while count > 0:
    print(count)
    count -= 1  # Subtracts 1 from count each time the loop runs

# Prints the final message after the countdown finishes
print("Time is up!")
